LCD_RA8889::LCD_RA8889()
  : displayEnabled(false), nativeDelegate(nullptr)
{
  framebuffer = new uint8_t[LCD_FB_SIZE];
  reset();
}

LCD_RA8889::~LCD_RA8889()
{
  delete[] framebuffer;
}

void LCD_RA8889::reset()
{
  memset(framebuffer, 0, LCD_FB_SIZE);
  memset(regs, 0, sizeof(regs));
  selectedReg = 0;

  displayEnable = false;
  canvasWidth = LCD_WIDTH;
  canvasHeight = LCD_HEIGHT;
  canvasAddr = 0;
  activeWinX = 0;
  activeWinY = 0;
  activeWinW = LCD_WIDTH;
  activeWinH = LCD_HEIGHT;
  mainWinX = 0;
  mainWinY = 0;

  textCursorX = 0;
  textCursorY = 0;
  textMode = false;
  fontSizeIdx = FONT_12x24;
  fontW = 12;
  fontH = 24;
  hScale = 1;
  vScale = 1;
  fgR = 255; fgG = 255; fgB = 255;
  bgR = 0; bgG = 0; bgB = 0;
  textTransparent = false;
  cursorVisible = false;
  cursorBlink = false;
  blinkRate = 30;
  charLineGap = 0;
  charSpacing = 0;

  drawBusy = false;
  drawX0 = drawY0 = drawX1 = drawY1 = 0;

  bteBusy = false;
  bteSrcX = bteSrcY = 0;
  bteDstX = bteDstY = 0;
  bteWidth = bteHeight = 0;

  pwmDuty = 255;  // full brightness
}

wdc816::Byte LCD_RA8889::getByte(wdc816::Addr offset)
{
  if (offset == 0) {
    // Status read: bit 7 = not busy (1 = ready)
    uint8_t status = 0x80;  // always ready (emulator is instant)
    return status;
  } else {
    return readRegister(selectedReg);
  }
}

void LCD_RA8889::setByte(wdc816::Addr offset, wdc816::Byte data)
{
  if (offset == 0) {
    // Write to register address port — select register
    selectedReg = data;
  } else {
    // Write to register data port
    writeRegister(selectedReg, data);
  }
}

uint8_t LCD_RA8889::readRegister(uint8_t reg)
{
  // Return stored register value for most registers
  return regs[reg];
}

void LCD_RA8889::writeRegister(uint8_t reg, uint8_t value)
{
  regs[reg] = value;

  switch (reg) {
  case 0x00: // SRR — Software Reset
    if (value & 0x01) {
      reset();
    }
    break;

  case 0x01: // CCR — Chip Configuration (display enable)
    displayEnable = (value & 0x80) != 0;
    dirty.store(true, std::memory_order_relaxed);
    break;

  case 0x03: // ICR — Mode Control
    textMode = (value & 0x04) != 0;
    break;

  case 0x04: // MRWDP — Memory Read/Write Data Port
    if (textMode) {
      fprintf(stderr, "[LCD] renderChar '%c' (0x%02X) at cursor (%d,%d) fg=(%d,%d,%d) bg=(%d,%d,%d)\n",
              (value >= 0x20 && value < 0x7F) ? value : '.', value,
              textCursorX, textCursorY, fgR, fgG, fgB, bgR, bgG, bgB);
      renderCharacter(value);
    }
    // Graphic mode pixel writes not needed for Forth kernel
    break;

  // Panel timing — accepted but no action needed in emulator
  case 0x05: case 0x07: case 0x09: case 0x0B:
  case 0x0E: case 0x0F:
  case 0x10: case 0x11: case 0x12: case 0x13: case 0x14:
  case 0x15: case 0x16: case 0x17: case 0x18: case 0x19: case 0x1A:
    break;

  // Main Window scroll offset
  case 0x26: mainWinX = (mainWinX & 0xFF00) | value; break;
  case 0x27: mainWinX = (mainWinX & 0x00FF) | (value << 8); break;
  case 0x28: mainWinY = (mainWinY & 0xFF00) | value; break;
  case 0x29: mainWinY = (mainWinY & 0x00FF) | (value << 8); break;

  case 0x40: // MWCR0 — Cursor control
    cursorVisible = (value & 0x40) != 0;
    cursorBlink = (value & 0x20) != 0;
    dirty.store(true, std::memory_order_relaxed);
    break;

  case 0x44: // BTCR — Blink Time Control
    blinkRate = value;
    break;

  // Canvas Start Address
  case 0x50: canvasAddr = (canvasAddr & 0xFFFFFF00) | value; break;
  case 0x51: canvasAddr = (canvasAddr & 0xFFFF00FF) | ((uint32_t)value << 8); break;
  case 0x52: canvasAddr = (canvasAddr & 0xFF00FFFF) | ((uint32_t)value << 16); break;
  case 0x53: canvasAddr = (canvasAddr & 0x00FFFFFF) | ((uint32_t)value << 24); break;

  // Canvas Image Width
  case 0x54: canvasWidth = (canvasWidth & 0xFF00) | value; break;
  case 0x55: canvasWidth = (canvasWidth & 0x00FF) | (value << 8); break;

  // Active Window Upper-Left
  case 0x56: activeWinX = (activeWinX & 0xFF00) | value; break;
  case 0x57: activeWinX = (activeWinX & 0x00FF) | (value << 8); break;
  case 0x58: activeWinY = (activeWinY & 0xFF00) | value; break;
  case 0x59: activeWinY = (activeWinY & 0x00FF) | (value << 8); break;

  // Active Window Size
  case 0x5A: activeWinW = (activeWinW & 0xFF00) | value; break;
  case 0x5B: activeWinW = (activeWinW & 0x00FF) | (value << 8); break;
  case 0x5C: activeWinH = (activeWinH & 0xFF00) | value; break;
  case 0x5D: activeWinH = (activeWinH & 0x00FF) | (value << 8); break;

  case 0x5E: // AW_COLOR — Color Depth (ignored, always 16bpp in emulator)
    break;

  // Text Cursor X/Y
  case 0x63: textCursorX = (textCursorX & 0xFF00) | value; break;
  case 0x64: textCursorX = (textCursorX & 0x00FF) | (value << 8); break;
  case 0x65: textCursorY = (textCursorY & 0xFF00) | value; break;
  case 0x66: textCursorY = (textCursorY & 0x00FF) | (value << 8); break;

  case 0x67: // DCR0 — Drawing Control
    if (value & 0x80) {
      // Start bit set — execute drawing
      executeDrawing();
    }
    break;

  // Drawing coordinates
  case 0x68: drawX0 = (drawX0 & 0xFF00) | value; break;
  case 0x69: drawX0 = (drawX0 & 0x00FF) | (value << 8); break;
  case 0x6A: drawY0 = (drawY0 & 0xFF00) | value; break;
  case 0x6B: drawY0 = (drawY0 & 0x00FF) | (value << 8); break;
  case 0x6C: drawX1 = (drawX1 & 0xFF00) | value; break;
  case 0x6D: drawX1 = (drawX1 & 0x00FF) | (value << 8); break;
  case 0x6E: drawY1 = (drawY1 & 0xFF00) | value; break;
  case 0x6F: drawY1 = (drawY1 & 0x00FF) | (value << 8); break;

  // PWM registers
  case 0x84: case 0x85: case 0x86:
    break;
  case 0x87: // TCMPB0L — PWM duty cycle low
    pwmDuty = value;
    dirty.store(true, std::memory_order_relaxed);
    break;
  case 0x88: // TCMPB0H
    break;

  case 0x90: // BTE_CTRL0 — ROP code
    break;
  case 0x91: // BTE_CTRL1 — writing operation code triggers execution
    if (value != 0) {
      executeBTE();
    }
    break;

  // BTE source X/Y (using XY coordinate mode)
  case 0x98: bteSrcX = (bteSrcX & 0xFF00) | value; break;
  case 0x99: bteSrcX = (bteSrcX & 0x00FF) | (value << 8); break;
  case 0x9A: bteSrcY = (bteSrcY & 0xFF00) | value; break;
  case 0x9B: bteSrcY = (bteSrcY & 0x00FF) | (value << 8); break;

  // BTE dest X/Y
  case 0xA2: bteDstX = (bteDstX & 0xFF00) | value; break;
  case 0xA3: bteDstX = (bteDstX & 0x00FF) | (value << 8); break;
  case 0xA4: bteDstY = (bteDstY & 0xFF00) | value; break;
  case 0xA5: bteDstY = (bteDstY & 0x00FF) | (value << 8); break;

  // BTE width/height
  case 0xA6: bteWidth = (bteWidth & 0xFF00) | value; break;
  case 0xA7: bteWidth = (bteWidth & 0x00FF) | (value << 8); break;
  case 0xA8: bteHeight = (bteHeight & 0xFF00) | value; break;
  case 0xA9: bteHeight = (bteHeight & 0x00FF) | (value << 8); break;

  case 0xCC: // CCR0 — Font size + encoding
    fontSizeIdx = (value >> 4) & 0x03;
    updateFontSize();
    break;

  case 0xCD: // CCR1 — Transparency, rotation, scaling
    textTransparent = (value & 0x01) != 0;
    // Bit 4 = rotation (not implemented)
    hScale = ((value >> 2) & 0x03) + 1;
    vScale = ((value >> 4) & 0x03) + 1;
    // Re-read scaling bits: bits[3:2] = H scale, bits[5:4] = V scale
    // Actually RA8889: bits[3:2]=Hscale-1, bits[5:4]=Vscale-1
    hScale = ((value >> 2) & 0x03) + 1;
    vScale = ((value >> 4) & 0x03) + 1;
    break;

  case 0xD0: // FLDR — Character Line Gap
    charLineGap = value;
    break;

  case 0xD1: // F2FSSR — Character Spacing
    charSpacing = value;
    break;

  // Foreground color
  case 0xD2: fgR = value; fprintf(stderr, "[LCD] FG R=%d\n", value); dirty.store(true, std::memory_order_relaxed); break;
  case 0xD3: fgG = value; fprintf(stderr, "[LCD] FG G=%d\n", value); dirty.store(true, std::memory_order_relaxed); break;
  case 0xD4: fgB = value; fprintf(stderr, "[LCD] FG B=%d\n", value); dirty.store(true, std::memory_order_relaxed); break;

  // Background color
  case 0xD5: bgR = value; fprintf(stderr, "[LCD] BG R=%d\n", value); break;
  case 0xD6: bgG = value; fprintf(stderr, "[LCD] BG G=%d\n", value); break;
  case 0xD7: bgB = value; fprintf(stderr, "[LCD] BG B=%d\n", value); break;

  default:
    // Unknown register — just stored in regs[]
    break;
  }
}

void LCD_RA8889::updateFontSize()
{
  switch (fontSizeIdx) {
  case FONT_8x16:  fontW = 8;  fontH = 16; break;
  case FONT_12x24: fontW = 12; fontH = 24; break;
  case FONT_16x32: fontW = 16; fontH = 32; break;
  default:         fontW = 12; fontH = 24; break;
  }
}

void LCD_RA8889::renderCharacter(uint8_t ch)
{
  // Base glyph from 8x16 CGROM
  const uint8_t *glyph = &cgrom_8x16[ch * 16];

  int effectiveW = fontW * hScale;
  int effectiveH = fontH * vScale;

  for (int py = 0; py < effectiveH; py++) {
    for (int px = 0; px < effectiveW; px++) {
      int fx = px / hScale;
      int fy = py / vScale;

      // Map from target font size back to 8x16 base
      int baseX, baseY;
      switch (fontSizeIdx) {
      case FONT_8x16:
        baseX = fx;
        baseY = fy;
        break;
      case FONT_12x24:
        // Scale 8x16 to 12x24: multiply by 1.5
        baseX = fx * 8 / 12;
        baseY = fy * 16 / 24;
        break;
      case FONT_16x32:
        // Scale 8x16 to 16x32: multiply by 2
        baseX = fx / 2;
        baseY = fy / 2;
        break;
      default:
        baseX = fx * 8 / 12;
        baseY = fy * 16 / 24;
        break;
      }

      if (baseX >= 8) baseX = 7;
      if (baseY >= 16) baseY = 15;

      bool pixel = (glyph[baseY] >> (7 - baseX)) & 1;

      int screenX = textCursorX + px;
      int screenY = textCursorY + py;

      if (screenX >= 0 && screenX < LCD_WIDTH &&
          screenY >= 0 && screenY < LCD_HEIGHT) {
        if (pixel) {
          setPixel(screenX, screenY, fgR, fgG, fgB);
        } else if (!textTransparent) {
          setPixel(screenX, screenY, bgR, bgG, bgB);
        }
      }
    }
  }

  advanceTextCursor();
  dirty.store(true, std::memory_order_relaxed);
}

void LCD_RA8889::advanceTextCursor()
{
  int effectiveW = fontW * hScale;
  int effectiveH = fontH * vScale;

  textCursorX += effectiveW + charSpacing;
  if (textCursorX + effectiveW > (int)canvasWidth) {
    textCursorX = 0;
    textCursorY += effectiveH + charLineGap;
  }

  // Update cursor position registers
  regs[0x63] = textCursorX & 0xFF;
  regs[0x64] = (textCursorX >> 8) & 0xFF;
  regs[0x65] = textCursorY & 0xFF;
  regs[0x66] = (textCursorY >> 8) & 0xFF;
}

void LCD_RA8889::executeDrawing()
{
  uint8_t dcr0 = regs[0x67];
  // Bits [4:3]: shape  00=line, 01=rect, 10=triangle
  // Bit 5: fill (for rect/tri)
  // Bit 7: start (already checked)
  int shape = (dcr0 >> 3) & 0x03;
  bool fill = (dcr0 & 0x20) != 0;

  switch (shape) {
  case 0: // Line
    drawLine(drawX0, drawY0, drawX1, drawY1);
    break;
  case 1: // Rectangle
    drawRect(drawX0, drawY0, drawX1, drawY1, fill);
    break;
  default:
    // Triangle etc. — not used by Forth kernel
    break;
  }

  // Clear start bit
  regs[0x67] &= ~0x80;
  dirty.store(true, std::memory_order_relaxed);
}

void LCD_RA8889::executeBTE()
{
  uint8_t ctrl1 = regs[0x91];
  int op = (ctrl1 >> 1) & 0x07;  // operation code in bits [3:1]

  fprintf(stderr, "[LCD] BTE op=%d ctrl1=0x%02X dst=(%d,%d) src=(%d,%d) size=%dx%d fg=(%d,%d,%d)\n",
          op, ctrl1, bteDstX, bteDstY, bteSrcX, bteSrcY, bteWidth, bteHeight, fgR, fgG, fgB);
  switch (op) {
  case 0x01: // Memory copy (source copy)
    bteBlockCopy(bteSrcX, bteSrcY, bteDstX, bteDstY, bteWidth, bteHeight);
    break;
  case 0x03: // Solid fill
    bteSolidFill(bteDstX, bteDstY, bteWidth, bteHeight, fgR, fgG, fgB);
    break;
  default:
    fprintf(stderr, "[LCD] BTE: unhandled op %d\n", op);
    break;
  }

  // Clear start bit
  regs[0x91] &= ~0x01;
  dirty.store(true, std::memory_order_relaxed);
}

void LCD_RA8889::bteBlockCopy(uint16_t sx, uint16_t sy,
                               uint16_t dx, uint16_t dy,
                               uint16_t w, uint16_t h)
{
  // Copy rectangular region in framebuffer
  // Handle overlapping by choosing copy direction
  if (dy < sy || (dy == sy && dx < sx)) {
    // Copy top-to-bottom, left-to-right
    for (int row = 0; row < h; row++) {
      for (int col = 0; col < w; col++) {
        int srcOff = ((sy + row) * LCD_WIDTH + (sx + col)) * 2;
        int dstOff = ((dy + row) * LCD_WIDTH + (dx + col)) * 2;
        if (srcOff + 1 < LCD_FB_SIZE && dstOff + 1 < LCD_FB_SIZE) {
          framebuffer[dstOff] = framebuffer[srcOff];
          framebuffer[dstOff + 1] = framebuffer[srcOff + 1];
        }
      }
    }
  } else {
    // Copy bottom-to-top, right-to-left
    for (int row = h - 1; row >= 0; row--) {
      for (int col = w - 1; col >= 0; col--) {
        int srcOff = ((sy + row) * LCD_WIDTH + (sx + col)) * 2;
        int dstOff = ((dy + row) * LCD_WIDTH + (dx + col)) * 2;
        if (srcOff + 1 < LCD_FB_SIZE && dstOff + 1 < LCD_FB_SIZE) {
          framebuffer[dstOff] = framebuffer[srcOff];
          framebuffer[dstOff + 1] = framebuffer[srcOff + 1];
        }
      }
    }
  }
}

void LCD_RA8889::bteSolidFill(uint16_t x, uint16_t y,
                               uint16_t w, uint16_t h,
                               uint8_t r, uint8_t g, uint8_t b)
{
  uint16_t color = rgb565(r, g, b);
  uint8_t lo = color & 0xFF;
  uint8_t hi = (color >> 8) & 0xFF;

  for (int row = 0; row < h; row++) {
    for (int col = 0; col < w; col++) {
      int px = x + col;
      int py = y + row;
      if (px < LCD_WIDTH && py < LCD_HEIGHT) {
        int off = (py * LCD_WIDTH + px) * 2;
        framebuffer[off] = lo;
        framebuffer[off + 1] = hi;
      }
    }
  }
}

void LCD_RA8889::drawLine(int x0, int y0, int x1, int y1)
{
  // Bresenham's line algorithm
  int dx = abs(x1 - x0);
  int dy = -abs(y1 - y0);
  int sx = x0 < x1 ? 1 : -1;
  int sy = y0 < y1 ? 1 : -1;
  int err = dx + dy;

  while (true) {
    setPixel(x0, y0, fgR, fgG, fgB);
    if (x0 == x1 && y0 == y1) break;
    int e2 = 2 * err;
    if (e2 >= dy) { err += dy; x0 += sx; }
    if (e2 <= dx) { err += dx; y0 += sy; }
  }
}

void LCD_RA8889::drawRect(int x0, int y0, int x1, int y1, bool fill)
{
  int minX = std::min(x0, x1);
  int maxX = std::max(x0, x1);
  int minY = std::min(y0, y1);
  int maxY = std::max(y0, y1);

  if (fill) {
    for (int y = minY; y <= maxY; y++)
      for (int x = minX; x <= maxX; x++)
        setPixel(x, y, fgR, fgG, fgB);
  } else {
    for (int x = minX; x <= maxX; x++) {
      setPixel(x, minY, fgR, fgG, fgB);
      setPixel(x, maxY, fgR, fgG, fgB);
    }
    for (int y = minY; y <= maxY; y++) {
      setPixel(minX, y, fgR, fgG, fgB);
      setPixel(maxX, y, fgR, fgG, fgB);
    }
  }
}

void LCD_RA8889::setPixel(int x, int y, uint8_t r, uint8_t g, uint8_t b)
{
  if (x < 0 || x >= LCD_WIDTH || y < 0 || y >= LCD_HEIGHT) return;
  uint16_t color = rgb565(r, g, b);
  int off = (y * LCD_WIDTH + x) * 2;
  framebuffer[off] = color & 0xFF;
  framebuffer[off + 1] = (color >> 8) & 0xFF;
}

uint16_t LCD_RA8889::rgb565(uint8_t r, uint8_t g, uint8_t b)
{
  return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

