// ---------------------------------------------------------------------------
// LCDView — custom NSView that renders RA8889 RGB565 framebuffer
// ---------------------------------------------------------------------------

@interface LCDView : NSView {
  LCD_RA8889 *lcd;
  uint8_t *rgbaBuffer;
  int blinkCounter;
  bool blinkState;
}
- (instancetype)initWithFrame:(NSRect)frame lcd:(LCD_RA8889 *)l;
- (void)refresh;
@end

@implementation LCDView

- (instancetype)initWithFrame:(NSRect)frame lcd:(LCD_RA8889 *)l {
  self = [super initWithFrame:frame];
  if (self) {
    lcd = l;
    rgbaBuffer = (uint8_t *)calloc(LCD_WIDTH * LCD_HEIGHT, 4);
    blinkCounter = 0;
    blinkState = true;
  }
  return self;
}

- (void)dealloc {
  free(rgbaBuffer);
  [super dealloc];
}

- (void)refresh {
  if (lcd->dirty.exchange(false)) {
    [self setNeedsDisplay:YES];
  }
  // Update blink state for cursor
  blinkCounter++;
  int rate = lcd->getBlinkRate();
  if (rate == 0) rate = 30;
  if (blinkCounter >= rate) {
    blinkCounter = 0;
    blinkState = !blinkState;
    if (lcd->isCursorVisible() && lcd->isCursorBlink()) {
      [self setNeedsDisplay:YES];
    }
  }
}

- (BOOL)acceptsFirstResponder {
  return YES;
}

- (void)keyDown:(NSEvent *)event {
  NSString *raw = [event charactersIgnoringModifiers];
  if ([raw length] == 0) return;

  unichar base = [raw characterAtIndex:0];
  if (base >= 0xF700) return;

  NSUInteger flags = [event modifierFlags];
  bool shift = (flags & NSEventModifierFlagShift) != 0;
  bool ctrl  = (flags & NSEventModifierFlagControl) != 0;

  unsigned char ch;

  if (ctrl && base >= 'a' && base <= 'z') {
    ch = base - 'a' + 1;
  } else if (base == '\r' || base == '\n') {
    ch = 0x0D;
  } else if (base == 0x7F || base == 0x08) {
    ch = 0x08;
  } else if (base == 0x1B) {
    ch = 0x1B;
  } else if (base == 0x09) {
    ch = 0x09;
  } else if (shift) {
    NSString *chars = [event characters];
    if ([chars length] == 0) return;
    unichar sch = [chars characterAtIndex:0];
    if (sch >= 0x80) return;
    ch = (unsigned char)sch;
  } else {
    if (base >= 0x80) return;
    ch = (unsigned char)base;
  }

  mem816::getL28MCU().injectChar(ch);
}

- (void)drawRect:(NSRect)dirtyRect {
  (void)dirtyRect;

  uint8_t *fb = lcd->getFramebuffer();
  float brightness = lcd->getPWMDuty() / 255.0f;

  // Convert RGB565 framebuffer to RGBA
  for (int row = 0; row < LCD_HEIGHT; row++) {
    for (int col = 0; col < LCD_WIDTH; col++) {
      int fbIdx = (row * LCD_WIDTH + col) * 2;
      uint16_t rgb = fb[fbIdx] | (fb[fbIdx + 1] << 8);
      uint8_t r = ((rgb >> 11) & 0x1F) << 3;
      uint8_t g = ((rgb >> 5) & 0x3F) << 2;
      uint8_t b = (rgb & 0x1F) << 3;

      // Apply brightness
      r = (uint8_t)(r * brightness);
      g = (uint8_t)(g * brightness);
      b = (uint8_t)(b * brightness);

      int off = (row * LCD_WIDTH + col) * 4;
      rgbaBuffer[off + 0] = r;
      rgbaBuffer[off + 1] = g;
      rgbaBuffer[off + 2] = b;
      rgbaBuffer[off + 3] = 255;
    }
  }

  // Draw cursor overlay
  if (lcd->isCursorVisible() && (!lcd->isCursorBlink() || blinkState)) {
    int cx = lcd->getTextCursorX();
    int cy = lcd->getTextCursorY();
    int fw = lcd->getFontW();
    int fh = lcd->getFontH();
    for (int dy = 0; dy < fh && (cy + dy) < LCD_HEIGHT; dy++) {
      for (int dx = 0; dx < fw && (cx + dx) < LCD_WIDTH; dx++) {
        int off = ((cy + dy) * LCD_WIDTH + (cx + dx)) * 4;
        // Invert colors for cursor
        rgbaBuffer[off + 0] ^= 0xFF;
        rgbaBuffer[off + 1] ^= 0xFF;
        rgbaBuffer[off + 2] ^= 0xFF;
      }
    }
  }

  CGColorSpaceRef cs = CGColorSpaceCreateDeviceRGB();
  CGContextRef bmpCtx = CGBitmapContextCreate(
    rgbaBuffer, LCD_WIDTH, LCD_HEIGHT, 8, LCD_WIDTH * 4, cs,
    kCGImageAlphaNoneSkipLast);
  CGImageRef image = CGBitmapContextCreateImage(bmpCtx);

  CGContextRef ctx = [[NSGraphicsContext currentContext] CGContext];

  // Fill background
  CGContextSetRGBFillColor(ctx, 0, 0, 0, 1.0);
  CGContextFillRect(ctx, self.bounds);

  // Draw framebuffer
  CGContextDrawImage(ctx,
    CGRectMake(0, 0, LCD_WIDTH, LCD_HEIGHT),
    image);

  CGImageRelease(image);
  CGContextRelease(bmpCtx);
  CGColorSpaceRelease(cs);
}

@end

// ---------------------------------------------------------------------------
// LCDDelegate — manages the NSWindow and refresh timer
// ---------------------------------------------------------------------------

@interface LCDDelegate : NSObject <NSApplicationDelegate, NSWindowDelegate> {
  LCD_RA8889 *lcd;
}
@property (nonatomic, strong) NSWindow *window;
@property (nonatomic, strong) NSTimer *refreshTimer;
@property (nonatomic, strong) LCDView *lcdView;
- (instancetype)initWithLCD:(LCD_RA8889 *)l;
@end

@implementation LCDDelegate

- (instancetype)initWithLCD:(LCD_RA8889 *)l {
  self = [super init];
  if (self) {
    lcd = l;
  }
  return self;
}

- (void)applicationDidFinishLaunching:(NSNotification *)notification {
  (void)notification;

  NSRect frame = NSMakeRect(100, 100, LCD_WIDTH, LCD_HEIGHT);
  self.window = [[NSWindow alloc]
    initWithContentRect:frame
    styleMask:(NSWindowStyleMaskTitled |
               NSWindowStyleMaskClosable |
               NSWindowStyleMaskMiniaturizable)
    backing:NSBackingStoreBuffered
    defer:NO];
  [self.window setTitle:@"L28 TFT Display (RA8889)"];
  [self.window setDelegate:self];

  self.lcdView = [[LCDView alloc]
    initWithFrame:NSMakeRect(0, 0, LCD_WIDTH, LCD_HEIGHT)
    lcd:lcd];
  [self.window setContentView:self.lcdView];
  [self.window makeKeyAndOrderFront:nil];

  // Refresh display at ~60 fps
  self.refreshTimer = [NSTimer scheduledTimerWithTimeInterval:1.0 / 60.0
    target:self
    selector:@selector(timerFired:)
    userInfo:nil
    repeats:YES];
}

- (void)timerFired:(NSTimer *)timer {
  (void)timer;
  [self.lcdView refresh];
}

- (void)windowWillClose:(NSNotification *)notification {
  (void)notification;
  [self.refreshTimer invalidate];
  self.refreshTimer = nil;
  emu816::stop();
  [NSApp terminate:nil];
}

- (BOOL)applicationShouldTerminateAfterLastWindowClosed:(NSApplication *)sender {
  (void)sender;
  return YES;
}

@end

