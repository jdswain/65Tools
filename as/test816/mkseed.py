# Writes Seed.Mod, which puts sample.s into the memory file system and
# sets the arguments of the assembler.
import sys
lines = open(sys.argv[1]).read().split('\n')
if lines[-1] == '': lines.pop()
out = ['MODULE Seed;', '  (* Generated by mkseed.py from sample.s. *)', '  IMPORT Files, Env;',
       '  VAR F: Files.File; R: Files.Rider;', '',
       '  PROCEDURE L(s: ARRAY OF CHAR);', '    VAR i: INTEGER;', '  BEGIN i := 0;',
       '    WHILE (i < LEN(s)) & (s[i] # 0X) DO', '      IF s[i] = "`" THEN Files.WriteByte(R, 22H) ELSE Files.WriteByte(R, ORD(s[i])) END;',
       '      INC(i)', '    END;', '    Files.WriteByte(R, 0AH)', '  END L;', '',
       'BEGIN', '  F := Files.New("sample.s"); Files.Set(R, F, 0);']
for l in lines:
    assert '`' not in l
    out.append('  L("%s");' % l.replace('"', '`'))
out += ['  Files.Register(F);', '  Env.Add("as"); Env.Add("-o"); Env.Add(OUT); Env.Add("sample.s")', 'END Seed.']
open('Seed.Mod', 'w').write('\n'.join(out).replace('OUT', '"%s"' % sys.argv[2]) + '\n')
