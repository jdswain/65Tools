# Writes Seed.Mod, which sets the assembler's arguments: as -o OUT sample.s.
# sample.s itself is on the floppy OS16 boots from (run.sh).
import sys
out = ['MODULE Seed;', '  (* Generated by mkseed.py: the arguments of the assembler. *)', '  IMPORT ASE;',
       'BEGIN', '  ASE.Add("as"); ASE.Add("-o"); ASE.Add("%s"); ASE.Add("sample.s")' % sys.argv[2], 'END Seed.']
open('Seed.Mod', 'w').write('\n'.join(out) + '\n')
